import { existsSync, mkdirSync, writeFileSync, rmSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { exec as execCb } from 'node:child_process'
import { promisify } from 'node:util'
import type { NginxRewriteRule, Project } from '../../shared/project.js'
import type { NativeBackend } from '../backends/native-backend.js'
import type { PrivilegedHelper } from '../core/privileged-helper.js'
import { paths } from '../core/paths.js'

const exec = promisify(execCb)

export interface VhostContext {
  project: Project
  /** Absolute docroot. For fpm/static this is what nginx serves from. */
  root: string
  /** fpm only: the PHP-FPM socket to fastcgi_pass to. */
  fpmSocket?: string
  /** fpm only: front controller filename from the framework driver. */
  frontController?: string
  /** fpm/static: extra location blocks from the framework driver. */
  rewrites?: NginxRewriteRule[]
  /** reverse-proxy only: the allocated upstream port. */
  proxyPort?: number
  /** TLS cert paths when the site is secured. */
  cert?: { certFile: string; keyFile: string }
}

/**
 * Nginx is the single front door for every `.test` domain regardless of serve
 * model — only what sits behind it changes. All three models render from this
 * one file; there are no per-project-type nginx branches anywhere else.
 */
export class NginxManager {
  constructor(
    private readonly native: NativeBackend,
    private readonly privileged: PrivilegedHelper
  ) {}

  vhostPath(project: Project): string {
    return join(paths.vhosts, `${project.domain}.conf`)
  }

  ensureRootConfig(): void {
    mkdirSync(paths.vhosts, { recursive: true })
    const main = join(paths.nginx, 'harbor.conf')
    if (!existsSync(main)) {
      writeFileSync(main, `include ${paths.vhosts}/*.conf;\n`, 'utf8')
    }
  }

  write(ctx: VhostContext): string {
    this.ensureRootConfig()
    const path = this.vhostPath(ctx.project)
    writeFileSync(path, this.render(ctx), 'utf8')
    return path
  }

  remove(project: Project): void {
    rmSync(this.vhostPath(project), { force: true })
  }

  render(ctx: VhostContext): string {
    const { project } = ctx
    const listen = ctx.cert
      ? ['listen 443 ssl;', 'listen [::]:443 ssl;', 'http2 on;']
      : ['listen 80;', 'listen [::]:80;']

    const tls = ctx.cert
      ? [`ssl_certificate ${ctx.cert.certFile};`, `ssl_certificate_key ${ctx.cert.keyFile};`]
      : []

    const body =
      project.serveModel === 'reverse-proxy'
        ? this.reverseProxyBody(ctx)
        : project.serveModel === 'fpm'
          ? this.fpmBody(ctx)
          : this.staticBody(ctx)

    return [
      `# Generated by Harbor for ${project.name} — do not edit by hand.`,
      'server {',
      indent([
        ...listen,
        `server_name ${project.domain};`,
        ...tls,
        `access_log ${join(paths.logs, `${project.domain}.access.log`)};`,
        `error_log ${join(paths.logs, `${project.domain}.error.log`)};`,
        'charset utf-8;',
        'client_max_body_size 512M;',
        ...body
      ]),
      '}',
      ''
    ].join('\n')
  }

  private reverseProxyBody(ctx: VhostContext): string[] {
    if (!ctx.proxyPort) throw new Error(`${ctx.project.name}: reverse-proxy vhost needs a port`)
    return [
      'location / {',
      ...indent([
        `proxy_pass http://127.0.0.1:${ctx.proxyPort};`,
        'proxy_http_version 1.1;',
        'proxy_set_header Upgrade $http_upgrade;',
        "proxy_set_header Connection 'upgrade';",
        'proxy_set_header Host $host;',
        'proxy_set_header X-Real-IP $remote_addr;',
        'proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;',
        'proxy_set_header X-Forwarded-Proto $scheme;',
        'proxy_cache_bypass $http_upgrade;',
        // Dev servers hold long-lived HMR sockets open.
        'proxy_read_timeout 3600s;'
      ]),
      '}'
    ]
  }

  private fpmBody(ctx: VhostContext): string[] {
    if (!ctx.fpmSocket) throw new Error(`${ctx.project.name}: fpm vhost needs a socket path`)
    const front = ctx.frontController ?? 'index.php'
    return [
      `root ${ctx.root};`,
      `index ${front};`,
      ...this.rewriteBlocks(ctx.rewrites),
      '',
      'location ~ \\.php$ {',
      ...indent([
        'include fastcgi_params;',
        `fastcgi_pass unix:${ctx.fpmSocket};`,
        'fastcgi_index index.php;',
        'fastcgi_split_path_info ^(.+\\.php)(/.+)$;',
        'fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;',
        'fastcgi_param PATH_INFO $fastcgi_path_info;',
        'fastcgi_param HTTPS $https if_not_empty;',
        'fastcgi_buffers 16 16k;',
        'fastcgi_buffer_size 32k;',
        'fastcgi_read_timeout 600;'
      ]),
      '}',
      '',
      'location ~ /\\.(?!well-known).* {',
      ...indent(['deny all;']),
      '}'
    ]
  }

  private staticBody(ctx: VhostContext): string[] {
    return [
      `root ${ctx.root};`,
      'index index.html index.htm;',
      ...this.rewriteBlocks(
        ctx.rewrites ?? [{ location: '/', directives: ['try_files $uri $uri/ /index.html;'] }]
      )
    ]
  }

  private rewriteBlocks(rules: NginxRewriteRule[] | undefined): string[] {
    if (!rules?.length) return []
    return rules.flatMap((rule) => [
      `location ${rule.location} {`,
      ...indent(rule.directives),
      '}'
    ])
  }

  async status(): Promise<{ installed: boolean; running: boolean; configPath: string | null }> {
    const binary = this.native.which('nginx')
    if (!binary) return { installed: false, running: false, configPath: null }
    const running = await exec('/usr/bin/pgrep -x nginx')
      .then(() => true)
      .catch(() => false)
    return { installed: true, running, configPath: join(paths.nginx, 'harbor.conf') }
  }

  /** Validate before reloading — a bad vhost must not take every site down. */
  async test(): Promise<{ ok: boolean; output: string }> {
    const binary = this.native.which('nginx')
    if (!binary) return { ok: false, output: 'nginx is not installed' }
    try {
      const { stderr } = await exec(`${binary} -t`)
      return { ok: true, output: stderr }
    } catch (err) {
      return { ok: false, output: (err as Error).message }
    }
  }

  /** Reload goes through PrivilegedHelper: nginx binds 80/443, so it needs root. */
  async reload(): Promise<void> {
    const check = await this.test()
    if (!check.ok) throw new Error(`nginx config test failed: ${check.output}`)
    const binary = this.native.which('nginx')
    await this.privileged.run(`${binary} -s reload`)
  }

  /** Read back a rendered vhost — used by the UI's "show config" affordance. */
  read(project: Project): string | null {
    const path = this.vhostPath(project)
    return existsSync(path) ? readFileSync(path, 'utf8') : null
  }
}

function indent(lines: string[], depth = 1): string[] {
  const pad = '    '.repeat(depth)
  return lines.map((l) => (l ? `${pad}${l}` : l))
}
